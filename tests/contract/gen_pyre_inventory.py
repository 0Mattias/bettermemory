def _tokens(text: str) -> list[tuple[int, str]]:
    """The positions and kinds of the spellings a mutant rewrites, outside
    classes: ``q`` a quantifier's end, ``{`` a counted repeat, ``$``,
    ``^``, ``Z`` for ``\\Z``, ``b`` for ``\\b``, ``|`` at depth 0."""
    out: list[tuple[int, str]] = []
    i, depth, in_class = 0, 0, False
    while i < len(text):
        c = text[i]
        if c == "\\":
            if not in_class and text[i + 1 : i + 2] in ("Z", "b"):
                out.append((i, text[i + 1]))
            i += 2
            continue
        if in_class:
            if c == "]" and text[i - 1] != "[" and text[i - 2 : i] != "[^":
                in_class = False
        elif c == "[":
            in_class = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        elif c in "*+?" and i > 0 and text[i - 1] not in "(":
            out.append((i, "q"))
        elif c == "{" and re.match(r"\{\d*,?\d*\}", text[i:]):
            out.append((i, "{"))
        elif c in "$^":
            out.append((i, c))
        elif c == "|" and depth == 0:
            out.append((i, "|"))
        i += 1
    return out


def _pattern_text(pattern: str | bytes) -> str:
    return pattern.decode("latin-1") if isinstance(pattern, bytes) else pattern


def _mutants(pattern: str | bytes, flags: int) -> list[tuple[str, str | bytes, int]]:
    is_bytes = isinstance(pattern, bytes)
    text = _pattern_text(pattern)
    out: list[tuple[str, str, int]] = []
    seen: dict[str, int] = {}

    def add(name: str, new: str, new_flags: int = flags) -> None:
        if seen.get(name, 0) >= 3:
            return
        seen[name] = seen.get(name, 0) + 1
        out.append((name, new, new_flags))

    toks = _tokens(text)
    for i, kind in toks:
        if kind == "q":
            lazy = text[i + 1 : i + 2] == "?"
            add(
                "lazy",
                text[: i + 1] + text[i + 2 :]
                if lazy
                else text[: i + 1] + "?" + text[i + 1 :],
            )
        elif kind == "{":
            end = text.index("}", i)
            body = text[i + 1 : end]
            lo, _, hi = body.partition(",")
            if lo.isdigit():
                add(
                    "bound",
                    text[: i + 1] + str(int(lo) + 1) + body[len(lo) :] + text[end:],
                )
            if hi.isdigit() and int(hi) > 0:
                add("bound", text[: i + 1] + lo + "," + str(int(hi) - 1) + text[end:])
        elif kind == "$":
            add("end", text[:i] + "\\Z" + text[i + 1 :])
        elif kind == "Z":
            add("end", text[:i] + "$" + text[i + 2 :])
        elif kind == "^":
            add("start", text[:i] + "\\A" + text[i + 1 :])
        elif kind == "b":
            add("boundary", text[:i] + text[i + 2 :])
    bars = [i for i, kind in toks if kind == "|"]
    if bars:
        first = text[: bars[0]]
        second = text[bars[0] + 1 : bars[1] if len(bars) > 1 else len(text)]
        rest = text[bars[1] :] if len(bars) > 1 else ""
        add("order", second + "|" + first + rest)
    for bit in (re.IGNORECASE, re.MULTILINE, re.DOTALL):
        if flags & bit:
            add("flag", text, flags & ~bit)
    if not is_bytes:
        add("ascii", text, flags | re.ASCII)
    result: list[tuple[str, str | bytes, int]] = []
    for name, new, new_flags in out:
        mutant: str | bytes = new.encode("latin-1") if is_bytes else new
        try:
            re.compile(mutant, new_flags)
        except (re.error, ValueError, OverflowError):
            continue
        result.append((name, mutant, new_flags))
    return result


def _neighbours(fragments: list[list[int]], alphabet: list[int]) -> list[list[int]]:
    """The near misses of each fragment: a symbol before or after it, one
    code point dropped, the fragment twice."""
    out: list[list[int]] = []
    for f in fragments:
        for c in alphabet:
            out += [[c, *f], [*f, c]]
        out += [f[:i] + f[i + 1 :] for i in range(len(f))]
        out.append(f + f)
    return out


def _differing(a: list[str], b: list[str]) -> list[int]:
    return [i for i, (x, y) in enumerate(zip(a, b, strict=True)) if x != y]


