"""Fixtures: every pattern of the reference the engine is to run, built
from the reference's own text and flags, against ``re`` itself (unit
pyre-7, tests only).

The sites are found anew at each generation (`_pyre_sites`): an ``ast``
scan of ``src/bettermemory`` for every call of ``re`` that takes a
pattern, and the patterns the modules build at import, read in a child
interpreter with ``re``'s functions wrapped. A site is one of three kinds:

- ``hand``: matched by a hand-written matcher already built (`HAND`, by
  id); pyre-8 proves those against the engine;
- ``builder``: a pattern built per call from data (`BUILDERS`, by id),
  the four data-built families, left to a later unit;
- ``engine``: every other site. Each distinct ``(pattern, flags)`` its
  instances hold is one ``inventory.pattern`` row.

**The tripwire.** Each site's line (id, kind, the SHA-256 of its
instances, the methods it is used through with their arguments' shape,
`_pyre_sites.Site.methods`) is pinned by `SITES_SHA256`: a new site, a
changed pattern text or flag, a method or a ``pos``, ``endpos``, count
or ``maxsplit`` argument added or gone, or a site gone fails the
generation, naming the lines that differ from the committed file's
``inventory.sites`` row.

**A pattern row** holds the pattern (`gen_pyre_tree.spell`), ``bytes``,
``flags``, ``sre_flags``, ``groups``, the group ``names``, the first 16
hex digits of the SHA-256 of ``str(re._parser.parse(pattern, flags))``
(``tree``), the sites, and the texts it is run over:

- ``alphabet``: one representative per cell of the pattern's own class
  partition (`_alphabet`): its literals, each range's ends and the code
  point past its end, a member of each category, and a fixed base;
- ``fragments``: up to `FRAGMENTS` texts drawn from the tree
  (`_witness`), a match or a near miss, with the texts that kill a mutant
  added (below);
- the texts, regenerated by the Rust test by the same rule (`texts`):
  every text over the alphabet of at most ``long`` code points (the
  largest bound with at most `EXHAUSTIVE` texts), then ``joined`` texts
  drawn by `gen_pyre_tree.Lcg` from ``seed``, each one to five pieces,
  each a fragment (two times in three when there are fragments), one with
  a code point dropped one time in four, or an alphabet symbol.

Each text is run through the five methods of `gen_pyre_api._line` over
the windows ``(0, n)`` and ``(1, n)``; the row holds the count of lines
and the SHA-256 over them. A pattern one of whose sites is used through
``sub``, ``subn`` or ``split`` also holds ``replace`` (those methods) and
the count and digest of the lines of `gen_pyre_api._replaced` over the
same texts: ``subn`` with ``<>``, ``subn_fn`` and ``split``, each with
every count of `REPLACE_COUNTS`. ``mutants`` counts the mutants killed and
those equivalent on the hidden pool.

**Mutants** (generator side only, `_mutants`): the pattern rewritten the
ways an engine could be wrong (greedy and lazy swapped, a bound off by
one, ``$`` for ``\\Z`` and back, ``^`` for ``\\A``, a ``\\b`` dropped, the
first two alternatives swapped, a flag dropped, ASCII classes), each
compiled by ``re``. A mutant is equivalent when no text of the committed
texts or of a hidden pool four times as large tells it apart; every
other mutant must be told apart by at least `KILL_MARGIN` committed
texts. Where the hidden pool finds a mutant the committed texts tell
apart too rarely, its first differing hidden texts become fragments, and
the texts are drawn again; a mutant that stays below the margin fails
the generation.

A pattern that folds case, or whose alphabet or fragments go past
ASCII, reads the Unicode tables: its row is in ``pyre_unicode.jsonl``
(`unicode_rows`), the rest in ``pyre_inventory.jsonl``.
"""

