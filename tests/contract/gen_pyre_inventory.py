def _patterns(sites: list[Site]) -> list[tuple[str | bytes, int, list[str]]]:
    found: dict[tuple[bool, str | bytes, int], list[str]] = {}
    for site in sites:
        if _kind(site) != "engine":
            continue
        for pattern, flags in site.instances:
            found.setdefault((isinstance(pattern, bytes), pattern, flags), []).append(
                site.id
            )
    return [(p, f, sorted(set(ids))) for (_, p, f), ids in sorted(found.items())]


def _seed(index: int) -> int:
    return SEED + index


def _replace_lines(
    compiled: re.Pattern[Any], is_bytes: bool, pool: list[list[int]]
) -> list[str]:
    repl: Any = b"<>" if is_bytes else "<>"
    return [
        " ".join(
            _replaced(compiled, method, repl, _as(is_bytes, codes), count)
            for method in ("subn", "subn_fn", "split")
            for count in REPLACE_COUNTS
        )
        for codes in pool
    ]


def _row(
    index: int,
    pattern: str | bytes,
    flags: int,
    sites: list[str],
    methods: dict[str, list[str]],
) -> dict[str, Any]:
    is_bytes = isinstance(pattern, bytes)
    compiled = re.compile(pattern, flags)
    tree = P.parse(pattern, flags)
    fold = bool(compiled.flags & re.IGNORECASE)
    alphabet = _alphabet(tree, is_bytes)
    fragments = _fragments(tree, alphabet, fold, is_bytes)
    seed = _seed(index)
    hidden = texts(alphabet, fragments, seed ^ 0xFFFF, JOINED * HIDDEN)[
        -JOINED * HIDDEN :
    ]
    mutants = [(m, f, re.compile(m, f)) for _, m, f in _mutants(pattern, flags)]
    hidden_base = _quick(compiled, is_bytes, hidden)
    hidden_mut = [_quick(c, is_bytes, hidden) for _, _, c in mutants]
    witnesses: list[list[int]] = []
    while True:
        pool = texts(alphabet, fragments, seed, JOINED) + witnesses
        base = _quick(compiled, is_bytes, pool)
        killed = equivalent = 0
        short: list[tuple[int, int]] = []
        for k, (_, _, c) in enumerate(mutants):
            here = len(_differing(base, _quick(c, is_bytes, pool)))
            there = _differing(hidden_base, hidden_mut[k])
            if here >= KILL_MARGIN:
                killed += 1
            elif here == 0 and not there:
                equivalent += 1
            else:
                short.append((k, here))
        if not short:
            break
        added = False
        for k, _ in short:
            for i in _differing(hidden_base, hidden_mut[k])[:2]:
                w = hidden[i]
                if w and w not in fragments and len(fragments) < MAX_FRAGMENTS:
                    fragments.append(w)
                    added = True
        if added:
            continue
        rng = Lcg(seed)
        more = [
            w for w in (_witness(tree, alphabet, rng, fold) for _ in range(MORE)) if w
        ]
        if is_bytes:
            more = [w for w in more if max(w) < 256]
        for k, here in short:
            need = KILL_MARGIN - here
            c = mutants[k][2]
            for r in range(DEEP_ROUNDS + 1):
                deep = (
                    _neighbours(fragments + more, alphabet)
                    if r == 0
                    else texts(alphabet, fragments, seed ^ (0x10000 + r), DEEP)[-DEEP:]
                )
                for i in _differing(
                    _quick(compiled, is_bytes, deep), _quick(c, is_bytes, deep)
                ):
                    if need > 0 and deep[i] not in pool and deep[i] not in witnesses:
                        witnesses.append(deep[i])
                        need -= 1
                if need <= 0:
                    break
            if need > 0:
                shown = (mutants[k][0], mutants[k][1])
                raise AssertionError(
                    f"a mutant told apart too rarely for {pattern!r}: {shown}"
                )
    lines = _lines(compiled, is_bytes, pool)
    digest = hashlib.sha256("".join(line + "\n" for line in lines).encode("ascii"))
    text = _pattern_text(pattern)
    names = sorted((i, n) for n, i in compiled.groupindex.items())
    row: dict[str, Any] = {
        "part": "inventory.pattern",
        "pattern": spell(text),
        "bytes": is_bytes,
        "sre_flags": compiled.flags,
        "groups": compiled.groups,
        "names": [[i, n] for i, n in names],
        "tree": hashlib.sha256(str(tree).encode("utf-8", "surrogatepass")).hexdigest()[
            :16
        ],
        "sites": sites,
        "alphabet": alphabet,
        "fragments": [_spelled(f) for f in fragments],
        "long": _long(len(alphabet)),
        "seed": seed,
        "witnesses": [_spelled(w) for w in witnesses],
        "count": len(lines),
        "sha16": digest.hexdigest()[:16],
        "mutants": [killed, equivalent],
    }
    if flags:
        row["flags"] = flags
    used = sorted(
        {m.split("/")[0] for site in sites for m in methods[site]} & REPLACING
    )
    if used:
        replace = _replace_lines(compiled, is_bytes, pool)
        joined = "".join(line + "\n" for line in replace).encode("ascii")
        row["replace"] = used
        row["replace_count"] = len(replace)
        row["replace_sha16"] = hashlib.sha256(joined).hexdigest()[:16]
    return row


_SHAPED = re.compile(r"[A-Za-z0-9_+/=-]{12,}|\\\\")


def _spelled(codes: list[int]) -> Any:
    """A text as written in a row: its code points when it holds a
    surrogate, a backslash (two are a host path to the fixture guard) or
    a run of twelve key-like characters (the credential detectors read a
    fixture line for key shapes); otherwise the string."""
    text = "".join(map(chr, codes))
    return [*codes] if has_surrogate(text) or _SHAPED.search(text) else text


def _unicode(row: dict[str, Any]) -> bool:
    wide = any(c > 127 for c in row["alphabet"]) or any(
        any((ord(ch) if isinstance(ch, str) else ch) > 127 for ch in f)
        for f in [*row["fragments"], *row["witnesses"]]
    )
    return bool(row["sre_flags"] & re.IGNORECASE) or wide


_CACHE: dict[str, Any] = {}


def _all() -> tuple[list[list[str]], list[dict[str, Any]]]:
    if not _CACHE:
        sites = _sites()
        lines = _site_lines(sites)
        _tripwire(lines)
        methods = {s.id: s.methods for s in sites}
        rows = [
            _row(i, p, f, ids, methods)
            for i, (p, f, ids) in enumerate(_patterns(sites))
        ]
        _CACHE["v"] = (lines, rows)
    return _CACHE["v"]


# ---------------------------------------------------------------------------
# The four data-built families.
# ---------------------------------------------------------------------------

#: Each family: the site, the source text of its pattern argument (pinned:
#: a change fails the generation), the flags, whether bytes, and inputs.
BUILDER_FAMILIES: list[tuple[str, str, str, int, bool, list[str]]] = [
    (
        "project_name",
        "scope_match.py:_project_name_matches.pattern",
        "f'(?<![A-Za-z0-9_.-]){token}(?![A-Za-z0-9_-]|\\\\.(?=\\\\S))'",
        re.IGNORECASE,
        False,
        ["bettermemory", "my-proj", "a.b-c", "x+y-z", "Uber-Name", "c++", "q_1-"],
    ),
    (
        "declared_root",
        "scope_match.py:_declared_root_spans.pattern",
        "re.escape(folded_needle)",
        re.IGNORECASE,
        False,
        ["/srv/proj", "C:/dir/a", "a.b*c", "~/x y", "Straße", "[x]"],
    ),
    (
        "column",
        "store_schema.py:_add_membership_tables.lacking",
        "f'\\\\b{column}\\\\b'",
        0,
        False,
        ["id", "store_id", "created_at", "x1"],
    ),
    (
        "packed_name",
        "githead.py:packed_names.line",
        "b'^[^\\\\n]* %s\\\\r?$' % re.escape(raw)",
        re.MULTILINE,
        True,
        ["refs/heads/main", "refs/tags/v1.0", "HEAD", "a b", "x.y+z"],
    ),
]

PREFIXES = ["", "x", "-", " ", ".", "/", "abc "]
SUFFIXES = ["", "x", "-", " ", ".", ".x", "\n", "\r\n", "\nz"]


def build_pattern(family: str, value: str) -> str:
    """The pattern text the reference's own string code builds."""
    if family == "project_name":
        token = "[-_.]".join(re.escape(seg) for seg in value.split("-"))
        return rf"(?<![A-Za-z0-9_.-]){token}(?![A-Za-z0-9_-]|\.(?=\S))"
    if family == "declared_root":
        return re.escape(value)
    if family == "column":
        return rf"\b{value}\b"
    return r"^[^\n]* " + re.escape(value) + r"\r?$"


def builder_texts(value: str) -> list[str]:
    return [p + value + s for p in PREFIXES for s in SUFFIXES]


def _source_of(site_id: str) -> str:
    import ast

    from ._pyre_sites import SOURCE

    rel, _, key = site_id.partition(":")
    tree = ast.parse((SOURCE / rel).read_text(encoding="utf-8"))
    scope, _, name = key.rpartition(".")
    for node in ast.walk(tree):
        if (
            isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
            and node.name == scope
        ):
            for call in ast.walk(node):
                if (
                    isinstance(call, ast.Call)
                    and isinstance(call.func, ast.Attribute)
                    and call.func.attr in ("compile", "search")
                    and call.args
                ):
                    return ast.unparse(call.args[0])
    raise AssertionError(site_id)


def _builder_rows() -> list[dict[str, Any]]:
    out = []
    for family, site, source, flags, is_bytes, inputs in BUILDER_FAMILIES:
        assert site in BUILDERS, site
        got = _source_of(site)
        assert got == source, f"the builder of {site} changed: {got}"
        digest = hashlib.sha256()
        count = 0
        for value in inputs:
            text = build_pattern(family, value)
            pattern: str | bytes = text.encode("latin-1") if is_bytes else text
            compiled = re.compile(pattern, flags)
            for t in builder_texts(value):
                subject = t.encode("latin-1") if is_bytes else t
                digest.update(
                    (_line(compiled, subject, 0, len(t)) + "\n").encode("ascii")
                )
                count += 1
        out.append(
            {
                "part": "inventory.builder",
                "family": family,
                "site": site,
                "flags": flags,
                "bytes": is_bytes,
                "inputs": inputs,
                "count": count,
                "sha16": digest.hexdigest()[:16],
            }
        )
    return out


def rows() -> list[dict[str, Any]]:
    lines, patterns = _all()
    return [
        {"part": "inventory.sites", "sites": lines},
        *[r for r in patterns if not _unicode(r)],
        *[r for r in _builder_rows() if not r["flags"] & re.IGNORECASE],
    ]


def unicode_rows() -> list[dict[str, Any]]:
    """The patterns and builders that fold case or read past ASCII."""
    return [
        *[r for r in _all()[1] if _unicode(r)],
        *[r for r in _builder_rows() if r["flags"] & re.IGNORECASE],
    ]


def generate() -> dict[str, bytes]:
    body = rows()
    head = {"part": "header", "fixture": "pyre_inventory", "rows": len(body)}
    return {"pyre_inventory.jsonl": jsonl([head, *body])}
