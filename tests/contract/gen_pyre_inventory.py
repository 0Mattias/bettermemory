_CATEGORY_REPS = {
    C.CATEGORY_DIGIT: "7",
    C.CATEGORY_NOT_DIGIT: "x",
    C.CATEGORY_SPACE: "\t",
    C.CATEGORY_NOT_SPACE: "y",
    C.CATEGORY_WORD: "k",
    C.CATEGORY_NOT_WORD: "@",
}


def _alphabet(tree: Any, is_bytes: bool) -> list[int]:
    found: list[int] = []

    def walk(data: Any) -> None:
        for op, av in data:
            if op in (C.LITERAL, C.NOT_LITERAL):
                found.append(av)
            elif op is C.IN:
                for o, a in av:
                    if o is C.LITERAL:
                        found.append(a)
                    elif o is C.RANGE:
                        found.extend([a[0], a[1], a[1] + 1])
                    elif o is C.CATEGORY:
                        found.append(ord(_CATEGORY_REPS[a]))
            elif op is C.BRANCH:
                for body in av[1]:
                    walk(body)
            elif op is C.SUBPATTERN:
                walk(av[3])
            elif op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
                walk(av[2])
            elif op in (C.ASSERT, C.ASSERT_NOT):
                walk(av[1])

    walk(tree.data)
    out: list[int] = []
    for c in [*found, *map(ord, BASE)]:
        if 0xD800 <= c <= 0xDFFF or c > 0x10FFFF or (is_bytes and c > 255):
            continue
        if c not in out:
            out.append(c)
    return out[:ALPHABET_CAP]


def _witness(tree: Any, alphabet: list[int], rng: Lcg, fold: bool) -> list[int]:
    out: list[int] = []

    def pick(seq: list[int]) -> int:
        return seq[rng.draw() % len(seq)]

    def walk(data: Any) -> None:
        for op, av in data:
            if op is C.LITERAL:
                c = av
                if fold and rng.draw() % 2:
                    swapped = chr(c).swapcase()
                    c = ord(swapped) if len(swapped) == 1 else c
                out.append(c)
            elif op in (C.NOT_LITERAL, C.ANY):
                out.append(pick(alphabet))
            elif op is C.IN:
                choices: list[int] = []
                for o, a in av:
                    if o is C.NEGATE:
                        choices = []
                        break
                    if o is C.LITERAL:
                        choices.append(a)
                    elif o is C.RANGE:
                        choices.append(a[0] + rng.draw() % (a[1] - a[0] + 1))
                    elif o is C.CATEGORY:
                        choices.append(ord(_CATEGORY_REPS[a]))
                out.append(pick(choices or alphabet))
            elif op is C.BRANCH:
                walk(av[1][rng.draw() % len(av[1])])
            elif op is C.SUBPATTERN:
                walk(av[3])
            elif op in (C.MAX_REPEAT, C.MIN_REPEAT, C.POSSESSIVE_REPEAT):
                lo, hi = av[0], av[1]
                top = lo + 3 if hi is C.MAXREPEAT or hi > lo + 3 else hi
                for _ in range(lo + rng.draw() % (top - lo + 1)):
                    walk(av[2])
            elif op is C.ASSERT and av[0] == 1:
                walk(av[1])

    walk(tree.data)
    return [c for c in out if not (0xD800 <= c <= 0xDFFF)]


def _fragments(
    tree: Any, alphabet: list[int], fold: bool, is_bytes: bool
) -> list[list[int]]:
    rng = Lcg(SEED)
    out: list[list[int]] = []
    for _ in range(FRAGMENTS * 4):
        w = _witness(tree, alphabet, rng, fold)
        if is_bytes and any(c > 255 for c in w):
            continue
        if w and w not in out and len(w) <= FRAGMENT_LEN:
            out.append(w)
        if len(out) == FRAGMENTS:
            break
    return out


def _long(k: int) -> int:
    n = 0
    while sum(k**i for i in range(n + 2)) <= EXHAUSTIVE:
        n += 1
    return n


def texts(
    alphabet: list[int], fragments: list[list[int]], seed: int, joined: int
) -> list[list[int]]:
    """The texts of a row: every text over the alphabet of at most
    `_long` code points, then ``joined`` texts drawn from ``seed``."""
    out = [
        list(t)
        for n in range(_long(len(alphabet)) + 1)
        for t in itertools.product(alphabet, repeat=n)
    ]
    rng = Lcg(seed)
    for _ in range(joined):
        text: list[int] = []
        for _ in range(1 + rng.draw() % 5):
            if fragments and rng.draw() % 3:
                piece = list(fragments[rng.draw() % len(fragments)])
                if rng.draw() % 4 == 0:
                    del piece[rng.draw() % len(piece)]
                text += piece
            else:
                text.append(alphabet[rng.draw() % len(alphabet)])
        out.append(text)
    return out


def _as(is_bytes: bool, codes: list[int]) -> Any:
    s = "".join(map(chr, codes))
    return s.encode("latin-1") if is_bytes else s


def _lines(
    compiled: re.Pattern[Any], is_bytes: bool, pool: list[list[int]]
) -> list[str]:
    out = []
    for codes in pool:
        t = _as(is_bytes, codes)
        n = len(codes)
        out.append(_line(compiled, t, 0, n))
        out.append(_line(compiled, t, 1, n))
    return out


def _quick(
    compiled: re.Pattern[Any], is_bytes: bool, pool: list[list[int]]
) -> list[str]:
    """What tells a mutant apart: every match of ``finditer`` with its
    groups, ``fullmatch`` and ``match`` from 1."""
    out = []
    for codes in pool:
        t = _as(is_bytes, codes)
        found = [m.regs for m in compiled.finditer(t)]
        full = compiled.fullmatch(t)
        one = compiled.match(t, 1)
        out.append(repr((found, full and full.regs, one and one.regs)))
    return out


