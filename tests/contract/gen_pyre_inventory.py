def _kind(site: Site) -> str:
    if site.id in BUILDERS:
        return "builder"
    if site.id in HAND:
        return "hand"
    return "engine"


def _instances_digest(site: Site) -> str:
    parts = [
        ("b" if isinstance(p, bytes) else "s")
        + (p.decode("latin-1") if isinstance(p, bytes) else p)
        + f"\x00{f}"
        for p, f in site.instances
    ]
    return hashlib.sha256(
        "\x01".join(parts).encode("utf-8", "surrogatepass")
    ).hexdigest()[:8]


def _site_lines(sites: list[Site]) -> list[list[str]]:
    return sorted(
        [s.id, _kind(s), _instances_digest(s), " ".join(s.methods)] for s in sites
    )


def _sites() -> list[Site]:
    sites = scan()
    failed = capture(sites)
    assert not failed, failed
    for site in sites:
        if site.id in BUILDERS:
            assert not site.instances, site.id
        else:
            assert site.instances, f"a site with no pattern: {site.id}"
    assert HAND <= {s.id for s in sites}, sorted(HAND - {s.id for s in sites})
    return sites


def _tripwire(lines: list[list[str]]) -> None:
    text = "".join("\t".join(line) + "\n" for line in lines)
    got = hashlib.sha256(text.encode("utf-8")).hexdigest()
    if got == SITES_SHA256:
        return
    committed: set[tuple[str, ...]] = set()
    try:
        from pathlib import Path
        import json

        path = Path(__file__).parent / "golden" / "pyre_inventory.jsonl"
        for raw in path.read_text(encoding="ascii").splitlines():
            row = json.loads(raw)
            if row.get("part") == "inventory.sites":
                committed = {tuple(x) for x in row["sites"]}
    except OSError:
        pass
    now = {tuple(x) for x in lines}
    raise AssertionError(
        "the reference's sites of re changed (decision section 4, the tripwire): "
        f"new or changed {sorted(now - committed)}; gone {sorted(committed - now)}; "
        f"sha256 {got}"
    )


