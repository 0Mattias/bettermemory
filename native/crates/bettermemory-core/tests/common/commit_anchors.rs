//! What the commit anchor tests share: one case of `commit_anchors.jsonl`
//! or `commit_anchors_posix.jsonl` run against `commit_anchors`, with the
//! generator's process (`gen_commit_anchors.py`): `os.getcwd()` answering
//! the header's `cwd`, the row's home and the header's users.

use std::cell::RefCell;
use std::rc::Rc;

use bettermemory_core::commit_anchors::{
    expected_home, project_commit_anchors, relative_under, Failure, PathHost,
};
use bettermemory_core::pyvalue::PyStr;
use bettermemory_core::unicode::{self, cps};
use bettermemory_core::verify_anchoring::anchor::{ClaimAnchor, TranslateFn};
use bettermemory_core::verify_candidates::scan::{getpwnam_refuses, UserHome};
use serde_json::{json, Map, Value};
use sha2::{Digest, Sha256};

/// This build's host with `os.getcwd()` answering the generator's `cwd`.
/// The rows of the file that is not gated answer alike under either
/// flavour, so on Windows they run under the Windows flavour.
pub fn here(cwd: &str) -> PathHost {
    PathHost::here(Ok(cps(cwd)))
}

pub fn text(v: &[u32]) -> Value {
    json!(unicode::to_string(v).expect("text"))
}

fn opt(v: &Value) -> Option<PyStr> {
    v.as_str().map(cps)
}

fn strs(v: &Value) -> Vec<String> {
    v.as_array()
        .map(|a| {
            a.iter()
                .map(|s| s.as_str().expect("text").to_string())
                .collect()
        })
        .unwrap_or_default()
}

/// The `ClaimAnchor` of `a` and the paths its `translate` was asked.
pub fn anchor_of(a: &Value) -> (Option<ClaimAnchor>, Rc<RefCell<Vec<String>>>) {
    let asked = Rc::new(RefCell::new(Vec::new()));
    if a.is_null() {
        return (None, asked);
    }
    let mut anchor = ClaimAnchor::new(
        a.get("root").and_then(|r| r.as_str()).map(str::to_string),
        a["rule"].as_str().expect("rule"),
    );
    anchor.recorded_roots = strs(a.get("rr").unwrap_or(&Value::Null));
    anchor.origin_root = a.get("or").and_then(opt);
    if let Some(table) = a.get("t") {
        let table: Map<String, Value> = table.as_object().expect("table").clone();
        let log = asked.clone();
        let translate: TranslateFn = Rc::new(move |path: &str| {
            log.borrow_mut().push(path.to_string());
            match table.get(path) {
                Some(v) => (
                    v[0].as_str().expect("target").to_string(),
                    v[1].as_str().expect("rule").to_string(),
                ),
                None => (path.to_string(), "absolute".to_string()),
            }
        });
        anchor.translate = Some(translate);
    }
    (Some(anchor), asked)
}

/// The generator's `pwd.getpwnam` over the header's users.
pub fn lookup_of(users: &Value) -> impl FnMut(&[u32]) -> UserHome + '_ {
    move |name: &[u32]| {
        if getpwnam_refuses(name) {
            return UserHome::Refused;
        }
        let name = unicode::to_string(name).expect("text");
        match users.get(&name).and_then(Value::as_str) {
            Some(home) => UserHome::Found(cps(home)),
            None => UserHome::Unknown,
        }
    }
}

fn raised(e: Failure) -> Value {
    json!({"raise": match e {
        Failure::Os(_) => "OSError",
        Failure::Value => "ValueError",
        Failure::NotPorted => "NotPorted",
    }})
}

/// One sweep row's answers, regenerated by its rule: `(count, sha256)`.
pub fn sweep(case: &Value, host: &PathHost) -> (usize, String) {
    let alphabet: Vec<String> = strs(&case["alphabet"]);
    // `itertools.product` order: the last position turns fastest.
    let joined = |lo: usize, hi: usize| -> Vec<String> {
        let base = alphabet.len();
        let mut out = Vec::new();
        for n in lo..=hi {
            for code in 0..base.pow(n as u32) {
                let digit = |pos: usize| (code / base.pow((n - 1 - pos) as u32)) % base;
                out.push((0..n).map(|pos| alphabet[digit(pos)].as_str()).collect());
            }
        }
        out
    };
    let roots = joined(1, case["rmax"].as_u64().expect("rmax") as usize);
    let paths = joined(0, case["pmax"].as_u64().expect("pmax") as usize);
    let mut hash = Sha256::new();
    let mut count = 0;
    for root in &roots {
        let root = cps(root);
        for path in &paths {
            let answer = relative_under(&cps(path), Some(&root), host).expect("no failure");
            match answer {
                None => hash.update(b"-"),
                Some(a) => {
                    hash.update(b"=");
                    hash.update(unicode::to_string(&a).expect("text").as_bytes());
                }
            }
            hash.update(b"\n");
            count += 1;
        }
    }
    (count, super::hex(&hash.finalize()))
}

/// One case's answer, spelled as the generator spells it (`o`, and `tl`
/// where the anchor translates).
pub fn run(case: &Value, header: &Value, host: &PathHost) -> Value {
    match case["f"].as_str().expect("f") {
        "ru" => {
            let root = opt(&case["r"]);
            match relative_under(&cps(case["p"].as_str().expect("p")), root.as_deref(), host) {
                Ok(Some(found)) => json!({"o": text(&found)}),
                Ok(None) => json!({"o": null}),
                Err(e) => json!({"o": raised(e)}),
            }
        }
        "eh" => {
            let roots: Vec<PyStr> = strs(&case["roots"]).iter().map(|r| cps(r)).collect();
            json!({"o": expected_home(&cps(case["p"].as_str().expect("p")), &roots)})
        }
        "pca" => {
            let paths: Vec<PyStr> = strs(&case["paths"]).iter().map(|p| cps(p)).collect();
            let (anchor, asked) = anchor_of(&case["a"]);
            let home = opt(&case["home"]);
            let mut lookup = lookup_of(&header["users"]);
            let got =
                project_commit_anchors(&paths, anchor.as_ref(), host, home.as_deref(), &mut lookup);
            let o = match got {
                Ok(c) => json!({
                    "paths": c.paths.iter().map(|p| text(p)).collect::<Vec<_>>(),
                    "unmapped": c.unmapped,
                }),
                Err(e) => raised(e),
            };
            let mut out = json!({"o": o});
            if case.get("tl").is_some() {
                out["tl"] = json!(*asked.borrow());
            }
            out
        }
        "sweep" => {
            let (count, sha) = sweep(case, host);
            json!({"count": count, "sha256": sha})
        }
        other => panic!("unknown case {other}"),
    }
}

/// What a case expects, in [`run`]'s spelling.
pub fn want(case: &Value) -> Value {
    if case["f"] == "sweep" {
        return json!({"count": case["count"], "sha256": case["sha256"]});
    }
    let mut out = json!({"o": case["o"]});
    if let Some(tl) = case.get("tl") {
        out["tl"] = tl.clone();
    }
    out
}

/// Every case of `file` against the port; the count checked.
pub fn every_case(test: &str, file: &str) {
    let lines = super::jsonl(file);
    let header = &lines[0];
    assert_eq!(header["k"], "header");
    let host = here(header["cwd"].as_str().expect("cwd"));
    let count = header["count"].as_u64().expect("a count") as usize;
    let mut ledger = super::parity::Ledger::new(test, file);
    let mut checked = 0;
    for (i, case) in lines[1..].iter().enumerate() {
        let got = run(case, header, &host);
        let label = format!("line {}", i + 2);
        assert!(
            !ledger.differs_fatally(&label, got == want(case)),
            "{label} {case}: got {got}"
        );
        checked += 1;
    }
    assert!(checked > 0);
    assert_eq!(checked, count);
    ledger.finish(count);
}
